function getLang(): Lang {
  return localStorage.getItem(STORAGE_KEY) === "nl" ? "nl" : "en";
}

function t(key: string, vars?: Record<string, string | number>): string {
  const lang = getLang();
  let str = TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replace(new RegExp(`{{${k}}}`, "g"), String(vars[k]));
    }
  }
  return str;
}

function applyTranslations(): void {
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n")!);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html")!);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")!));
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")!));
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")!));
  });
  document.documentElement.lang = getLang();
  document.querySelectorAll<HTMLElement>("[data-lang-switch]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang-switch") === getLang());
  });
}

function setLang(lang: Lang): void {
  localStorage.setItem(STORAGE_KEY, lang);
  applyTranslations();
}

export const BromeoI18n = { getLang, setLang, t, applyTranslations };
